#include "renderer/vulkan/vk_grid.h"
#include "renderer/vulkan/vk_pipeline.h"
#include "renderer/vulkan/vk_shader.h"

namespace gfx {

VulkanGridRenderer::~VulkanGridRenderer() {
    shutdown();
}

void VulkanGridRenderer::destroy_pipeline() {
    if (m_device != VK_NULL_HANDLE) {
        if (m_pipeline != VK_NULL_HANDLE) {
            vkDestroyPipeline(m_device, m_pipeline, nullptr);
        }

        if (m_pipeline_layout != VK_NULL_HANDLE) {
            vkDestroyPipelineLayout(
                m_device, m_pipeline_layout, nullptr);
        }
    }

    m_pipeline = VK_NULL_HANDLE;
    m_pipeline_layout = VK_NULL_HANDLE;
}

bool VulkanGridRenderer::init(VkDevice device, VkFormat color_format,
            VkFormat depth_format, VkDescriptorSetLayout descriptor_layout) {

    // Rebuild the pipeline while keeping the renderer reusable
    destroy_pipeline();

    if (device == VK_NULL_HANDLE ||
        color_format == VK_FORMAT_UNDEFINED ||
        depth_format == VK_FORMAT_UNDEFINED ||
        descriptor_layout == VK_NULL_HANDLE) {
        LOG_ERROR("invalid arguments for Vulkan grid pipeline");
        return false;
    }

    m_device = device;

    VkPipelineLayoutCreateInfo layout_info{};
    layout_info.sType =
        VK_STRUCTURE_TYPE_PIPELINE_LAYOUT_CREATE_INFO;
    layout_info.setLayoutCount = 1;
    layout_info.pSetLayouts = &descriptor_layout;
    layout_info.pushConstantRangeCount = 0;
    layout_info.pPushConstantRanges = nullptr;

    if (!vk_ok(
            vkCreatePipelineLayout(
                m_device,
                &layout_info,
                nullptr,
                &m_pipeline_layout),
            "create grid pipeline layout")) {
        destroy_pipeline();
        return false;
    }

    VkShaderModule vertex_shader = load_shader_module(
        m_device, GFX_SHADER_DIR "/grid.vert.spv");

    if (vertex_shader == VK_NULL_HANDLE) {
        destroy_pipeline();
        return false;
    }

    VkShaderModule fragment_shader = load_shader_module(
        m_device, GFX_SHADER_DIR "/grid.frag.spv");

    if (fragment_shader == VK_NULL_HANDLE) {
        vkDestroyShaderModule(m_device, vertex_shader, nullptr);
        destroy_pipeline();
        return false;
    }

    VulkanPipelineDesc desc{};
    desc.vert = vertex_shader;
    desc.frag = fragment_shader;
    desc.layout = m_pipeline_layout;
    desc.color_format = color_format;
    desc.depth_format = depth_format;

    desc.depth_test = true;
    desc.depth_write = false;
    desc.blend = true;

    m_pipeline = create_graphics_pipeline(m_device, desc);

    vkDestroyShaderModule(m_device, fragment_shader, nullptr);
    vkDestroyShaderModule(m_device, vertex_shader, nullptr);

    if (m_pipeline == VK_NULL_HANDLE) {
        destroy_pipeline();
        return false;
    }

    LOG_INFO("Vulkan grid pipeline created");
    return true;
}

void VulkanGridRenderer::draw(VkCommandBuffer cmd,
        VkExtent2D extent, VkDescriptorSet descriptor_set) const {

    if (m_pipeline == VK_NULL_HANDLE ||
        m_pipeline_layout == VK_NULL_HANDLE ||
        cmd == VK_NULL_HANDLE ||
        descriptor_set == VK_NULL_HANDLE ||
        extent.width == 0 ||
        extent.height == 0) {
        return;
    }

    VkViewport viewport{};
    viewport.x = 0.0f;
    viewport.y = 0.0f;
    viewport.width = static_cast<float>(extent.width);
    viewport.height = static_cast<float>(extent.height);
    viewport.minDepth = 0.0f;
    viewport.maxDepth = 1.0f;

    VkRect2D scissor{};
    scissor.offset = {0, 0};
    scissor.extent = extent;

    vkCmdBindPipeline(
        cmd, VK_PIPELINE_BIND_POINT_GRAPHICS, m_pipeline);

    vkCmdSetViewport(cmd, 0, 1, &viewport);
    vkCmdSetScissor(cmd, 0, 1, &scissor);

    vkCmdBindDescriptorSets(
        cmd,
        VK_PIPELINE_BIND_POINT_GRAPHICS,
        m_pipeline_layout,
        0,
        1,
        &descriptor_set,
        0,
        nullptr);

    // Draw the fullscreen triangle generated by gl_VertexIndex
    vkCmdDraw(cmd, 3, 1, 0, 0);
}

void VulkanGridRenderer::shutdown() {
    destroy_pipeline();
    m_device = VK_NULL_HANDLE;
}

} // namespace gfx
